// Validation of what a visitor submits. Nothing from the browser is trusted.

import { BRAND_MAX_LENGTH, CUSTOM_CATEGORY_MAX_LENGTH, getCategory } from '../categories';
import { brandKey, casingLooksDeliberate, titleCaseBrand } from '../evidence/brand-match';
import type { CategoryId } from '../types';

export interface AuditInput {
  /** The brand name for display: as typed when its capitalisation looks deliberate, tidied otherwise. */
  brand: string;
  brandCasing: 'typed' | 'derived';
  categoryId: CategoryId;
  /** Display label, e.g. "Skincare" or the visitor's own category text. */
  categoryLabel: string;
  /** How the category reads in a sentence or search query. */
  categoryNoun: string;
  /** How its brands are referred to in a question, e.g. "skincare brands". */
  categoryPlural: string;
  /** Normalized brand + category, used for the 7-day cache and duplicate prevention. */
  cacheKey: string;
}

export type InputResult = { ok: true; value: AuditInput } | { ok: false; message: string };

const BRAND_PATTERN = /^[\p{L}\p{N} .&'’+\-!]+$/u;
const CATEGORY_PATTERN = /^[\p{L}\p{N} &\-]+$/u;

function tidy(value: unknown): string {
  if (typeof value !== 'string') return '';
  return value
    .normalize('NFKC')
    .replace(/[\u0000-\u001f\u007f]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

export function validateAuditInput(body: unknown): InputResult {
  if (typeof body !== 'object' || body === null) return { ok: false, message: 'Enter a brand name and choose a category.' };
  const record = body as Record<string, unknown>;

  const typed = tidy(record.brand);
  // "cetaphil" and "CETAPHIL" become "Cetaphil"; "CeraVe" and "H&M" are left exactly as typed.
  const brandCasing = casingLooksDeliberate(typed) ? ('typed' as const) : ('derived' as const);
  const brand = brandCasing === 'typed' ? typed : titleCaseBrand(typed.toLowerCase());
  if (brand.length < 2) return { ok: false, message: 'Enter a brand name (at least 2 characters).' };
  if (brand.length > BRAND_MAX_LENGTH) return { ok: false, message: `Brand names can be up to ${BRAND_MAX_LENGTH} characters.` };
  if (/https?:|www\.|\.com\b/i.test(brand)) return { ok: false, message: 'Enter the brand name, not a web address.' };
  if (!BRAND_PATTERN.test(brand) || !/[\p{L}\p{N}]/u.test(brand)) {
    return { ok: false, message: "Brand names can use letters, numbers, spaces and . & ' + - ! only." };
  }
  if (brandKey(brand) === '') return { ok: false, message: 'Enter a brand name.' };

  const category = getCategory(tidy(record.category));
  if (!category) return { ok: false, message: 'Choose a category.' };

  if (category.id !== 'other') {
    return {
      ok: true,
      value: {
        brand,
        brandCasing,
        categoryId: category.id,
        categoryLabel: category.label,
        categoryNoun: category.noun,
        categoryPlural: category.plural,
        cacheKey: `${category.id}:${brandKey(brand)}`,
      },
    };
  }

  const custom = tidy(record.customCategory);
  if (custom.length < 3) return { ok: false, message: 'Describe the category in a few words, for example "running shoes".' };
  if (custom.length > CUSTOM_CATEGORY_MAX_LENGTH) {
    return { ok: false, message: `Categories can be up to ${CUSTOM_CATEGORY_MAX_LENGTH} characters.` };
  }
  if (!CATEGORY_PATTERN.test(custom)) return { ok: false, message: 'Categories can use letters, numbers, spaces, & and - only.' };
  const customKey = brandKey(custom);
  if (customKey === '') return { ok: false, message: 'Describe the category in a few words.' };
  return {
    ok: true,
    value: {
      brand,
      brandCasing,
      categoryId: 'other',
      categoryLabel: custom,
      categoryNoun: custom.toLowerCase(),
      categoryPlural: `${custom.toLowerCase()} brands`,
      cacheKey: `other:${customKey}:${brandKey(brand)}`,
    },
  };
}

/** Audit ids are generated by the server; anything else is rejected before touching storage. */
export function isValidAuditId(id: unknown): id is string {
  return typeof id === 'string' && /^[a-z0-9]{16,40}$/.test(id);
}
